#include <stdio.h>

int main() {
    char grade = 'A';
    char dollar = '$';
    char digit = '7';

    printf("Grade 값: %c\n", grade);
    printf("Grade 아스키코드: %d\n", grade);

    printf("Dollar Sign 값: %c\n", dollar);
    printf("Dollar Sign 아스키코드: %d\n", dollar);
    
    printf("Digit 값: %c\n", digit);
    printf("Digit 아스키코드: %d\n", digit);

    return 0;
}